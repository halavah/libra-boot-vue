/**
 * 多系统切换 - 统一配置文件
 * 包含：视图文件夹映射、系统注册表、工具函数
 */

import { scanViewFoldersAndGenerateRoutes, generateMenusFromRoutes } from './route-scanner';

// ==================== 1. 视图文件夹映射配置 ====================

/**
 * 视图文件夹到系统的映射配置
 * 注意：只有实际存在且包含页面的文件夹才会被启用
 * 支持动态扩展：views, views2, views3, ... viewsN
 */
export const viewSystemMapping = {
  // views 文件夹对应系统1
  views: {
    systemId: 'system1',
    systemName: 'system1',
    systemTitle: '系统1',
    systemIcon: 'Grid',
    description: '系统1',
    orderNum: 1,
    enabled: true
  }

  // 不再需要手动配置 views2, views3 等
  // 系统会自动识别 views* 文件夹并生成配置
  // 如果需要自定义某个系统的配置，可以在这里添加对应的 views* 配置
  // 例如：
  // views2: {
  //   systemId: 'custom-system',
  //   systemName: 'customSystem',
  //   systemTitle: '自定义系统名',
  //   systemIcon: 'Star',
  //   description: '自定义描述',
  //   orderNum: 2,
  //   enabled: true
  // }
};

/**
 * 根据视图文件夹名自动生成系统配置
 * @param {string} viewFolder - 视图文件夹名（views, views2, views3, ...）
 * @returns {Object} 系统配置对象
 */
function generateDefaultSystemConfig(viewFolder) {
  // 从文件夹名提取序号
  // views -> 1, views2 -> 2, views3 -> 3, etc.
  const match = viewFolder.match(/^views(\d*)$/);
  const systemNum = match ? (match[1] || '1') : '1';

  return {
    systemId: `system${systemNum}`,
    systemName: `system${systemNum}`,
    systemTitle: `系统${systemNum}`,
    systemIcon: getDefaultSystemIcon(parseInt(systemNum)),
    description: `系统${systemNum}`,
    orderNum: parseInt(systemNum),
    enabled: true
  };
}

/**
 * 根据系统序号获取默认图标
 * @param {number} systemNum - 系统序号
 * @returns {string} 图标名称
 */
function getDefaultSystemIcon(systemNum) {
  const icons = ['Grid', 'Setting', 'Document', 'Files', 'Folder', 'Management', 'Monitor', 'DataBoard'];
  return icons[(systemNum - 1) % icons.length] || 'Grid';
}

/**
 * 根据视图文件夹名获取系统配置
 * @param {string} viewFolder - 视图文件夹名（views, views2, views3, ...）
 * @returns {Object} 系统配置对象
 */
export function getSystemConfigByViewFolder(viewFolder) {
  // 先查找手动配置
  const config = viewSystemMapping[viewFolder];

  // 如果有手动配置，使用手动配置
  if (config) {
    return config;
  }

  // 如果没有手动配置，自动生成默认配置
  return generateDefaultSystemConfig(viewFolder);
}

/**
 * 获取所有启用的视图文件夹配置
 * @returns {Array} 启用的视图文件夹配置列表
 */
export function getEnabledViewFolders() {
  return Object.entries(viewSystemMapping)
    .filter(([, config]) => config.enabled !== false)
    .map(([viewFolder, config]) => ({
      viewFolder,
      ...config
    }))
    .sort((a, b) => (a.orderNum || 999) - (b.orderNum || 999));
}

// ==================== 2. 系统注册表 ====================

// 是否启用自动路由扫描和菜单生成
const AUTO_SCAN_ENABLED = true;

// 扫描视图文件夹生成系统配置
let autoGeneratedSystems = [];
if (AUTO_SCAN_ENABLED) {
  const { routes, systems } = scanViewFoldersAndGenerateRoutes();

  // 为每个自动扫描的系统生成菜单
  autoGeneratedSystems = systems.map(system => {
    const menus = generateMenusFromRoutes(system.routes, system.id);
    console.log(`✅ ${system.title} 自动生成 ${menus.length} 个菜单模块`);
    return {
      ...system,
      menus: menus,
      autoGenerated: true
    };
  });

  console.log('🚀 自动扫描完成，生成了', autoGeneratedSystems.length, '个系统');
}

// 手动配置的系统（可选，用于覆盖自动扫描的配置）
const manualSystems = [
  // 如果需要手动配置，在这里添加
];

/**
 * 合并手动配置和自动生成的系统
 * 手动配置优先级更高
 */
function mergeSystems(autoSystems, manualSystems) {
  const systemMap = {};

  // 先添加自动生成的系统
  autoSystems.forEach(system => {
    systemMap[system.id] = system;
  });

  // 手动配置覆盖自动生成
  manualSystems.forEach(system => {
    if (systemMap[system.id]) {
      // 合并配置，手动配置优先
      systemMap[system.id] = {
        ...systemMap[system.id],
        ...system,
        menus: system.menus || systemMap[system.id].menus,
        pages: system.pages || systemMap[system.id].pages
      };
    } else {
      systemMap[system.id] = system;
    }
  });

  return Object.values(systemMap).sort((a, b) => (a.orderNum || 0) - (b.orderNum || 0));
}

/**
 * 系统注册表
 */
export const systemRegistry = {
  systems: mergeSystems(autoGeneratedSystems, manualSystems),
  defaultSystemId: 'system1',
  autoScanEnabled: AUTO_SCAN_ENABLED
};

// ==================== 3. 工具函数 ====================

/**
 * 获取所有已启用的系统
 */
export function getEnabledSystems() {
  return systemRegistry.systems.filter(sys => sys.enabled !== false && sys.hidden !== true);
}

/**
 * 根据ID获取系统配置
 */
export function getSystemById(systemId) {
  return systemRegistry.systems.find(sys => sys.id === systemId);
}

/**
 * 根据ID获取系统的菜单配置
 */
export function getSystemMenus(systemId) {
  const system = getSystemById(systemId);
  return system?.menus || [];
}

/**
 * 根据ID获取系统的页面配置
 */
export function getSystemPages(systemId) {
  const system = getSystemById(systemId);
  return system?.pages || {};
}

/**
 * 根据页面ID获取页面配置
 */
export function getPageConfig(systemId, pageId) {
  const pages = getSystemPages(systemId);
  return pages[pageId];
}

/**
 * 根据路径查找页面配置
 */
export function findPageByPath(systemId, pagePath) {
  const pages = getSystemPages(systemId);
  return Object.values(pages).find(page => page.path === pagePath);
}
